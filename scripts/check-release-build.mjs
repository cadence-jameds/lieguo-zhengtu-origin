import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import {readmeReleaseAssets} from './readme-release.mjs';
const read=p=>JSON.parse(readFileSync(p,'utf8')),metadata=read('.release/metadata.json'),version=read('dist/version.json'),pkg=read('dist/package.json');
assert.deepEqual(version,metadata);assert.equal(pkg.version,metadata.version);assert.equal(pkg.commitSha,metadata.commitSha);
assert.ok(metadata.history[0].notes.length);assert.match(metadata.commitSha,/^[a-f0-9]{40}$/);
const readme=readmeReleaseAssets(metadata);
assert.equal(readFileSync('dist/release/latest.svg','utf8'),readme.svg);
assert.equal(readFileSync('dist/release/index.html','utf8'),readme.html);
assert.ok(!readFileSync('dist/sw.js','utf8').includes('release/latest.svg'),'README assets must not enter the game precache');
const workerReleaseFile=`sw-release-${metadata.commitSha}.js`;
assert.ok(readFileSync('dist/sw.js','utf8').includes(workerReleaseFile),'Worker must import its build identity');
let listener,reply;
runInNewContext(readFileSync('dist/'+workerReleaseFile,'utf8'),{self:{addEventListener(type,handler){assert.equal(type,'message');listener=handler;}}});
listener({data:{type:'GET_APP_RELEASE'},ports:[{postMessage(data){reply=JSON.parse(JSON.stringify(data));}}]});
assert.deepEqual(reply,{version:metadata.version,contentSha:metadata.contentSha});
console.log(JSON.stringify({version:metadata.version,date:metadata.date,commitSha:metadata.commitSha,contentSha:metadata.contentSha,dirty:metadata.dirty,artifactsConsistent:true,workerIdentityConsistent:true}));
